import ActivityKit
import Foundation

// Описание Live Activity для распознавания чека.
//
// ВНИМАНИЕ: файл существует в ДВУХ копиях — здесь и в targets/scan/. Под
// нативного модуля и таргет виджета собираются раздельно, общего файла между
// ними не сделать: `_shared` из apple-targets связывает виджет с основным
// таргетом приложения, а модуль живёт отдельным подом.
//
// ActivityKit сопоставляет приложение и виджет по ИМЕНИ типа, а не по его
// содержимому. Поэтому расхождение в полях не вызовет ошибки компиляции —
// островок просто молча не появится, и без устройства это не отладить.
// Синхронность копий проверяет scripts/check-live-activity-sync.mjs (он же
// висит в CI перед сборкой).
//
// Правило простое: правишь один файл — прогоняешь скрипт, он перезапишет
// второй.

@available(iOS 16.2, *)
struct ScanActivityAttributes: ActivityAttributes {
  struct ContentState: Codable, Hashable {
    /// processing | done | error. Управляет иконкой, цветом и вёрсткой,
    /// но НЕ текстом — см. ниже.
    var status: String

    /// Готовые к показу строки. Язык интерфейса у нас лежит в настройках
    /// приложения (user_settings.language), а не в локали устройства, так что
    /// переводит JS, а Swift только рисует. Иначе островок говорил бы на языке
    /// системы, а само приложение — на выбранном, и это заметно.
    var title: String
    var subtitle: String

    /// Отформатированная сумма («452 Kč») либо пустая строка, пока её нет.
    var amount: String

    /// Границы шкалы прогресса, epoch-секунды. WidgetKit не умеет крутить
    /// бесконечный ProgressView — в виджетах анимация ограничена. Зато он
    /// сам анимирует ProgressView(timerInterval:), поэтому вместо честного
    /// процента отдаём ожидаемый интервал: полоса едет плавно и без обновлений
    /// активности.
    var startedAt: Double
    var estimatedEndAt: Double
  }

  /// Идентификатор скана. За время активности не меняется, нужен для отладки
  /// и восстановления после перезапуска приложения.
  var scanId: String
}
